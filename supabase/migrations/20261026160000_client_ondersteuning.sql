
-- =====================================================
-- MIGRATIE: CLIENT EN ONDERSTEUNING
-- =====================================================

-- -----------------------------------------------------
-- 1. CLIENT
-- -----------------------------------------------------

CREATE TABLE public.client (
                               id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               naam text NOT NULL,
                               email text NOT NULL,
                               user_id uuid DEFAULT auth.uid(),
                               type text,
                               CONSTRAINT client_client_id_key UNIQUE (user_id)
);

-- -----------------------------------------------------
-- 2. ONDERSTEUNING
-- -----------------------------------------------------

CREATE TABLE public.ondersteuning (
                                      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                      naam text NOT NULL,
                                      type text NOT NULL,
                                      user_id uuid,
                                      CONSTRAINT ondersteuning_user_id_key UNIQUE (user_id),
                                      CONSTRAINT ondersteuning_user_id_fkey
                                          FOREIGN KEY (user_id)
                                              REFERENCES auth.users(id)
                                              ON DELETE CASCADE
);
